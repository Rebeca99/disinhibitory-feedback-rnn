#!/usr/bin/env python3
"""Generate the thesis figure bundle for the stochastic feedback-gating chapter.

The wrapper calls the individual figure scripts and writes all finished figures
and compact tables to one directory. It assumes the stochastic hidden-switch
summary folders created on the cluster are already present.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--stochastic-summaries-root',
        default=os.path.expanduser('~/biornn_feedback_stochastic_bottleneck_pfc01_seeds/summaries'),
        help='Summaries root from the main stochastic hidden-switch analysis.',
    )
    parser.add_argument(
        '--frozen-root',
        default=os.path.expanduser('~/biornn_feedback_stochastic_frozen_backbone_pfc01_seeds'),
        help='Root directory from the frozen-backbone control run.',
    )
    parser.add_argument(
        '--output-dir',
        default=os.path.expanduser('~/biornn_feedback_stochastic_bottleneck_pfc01_seeds/summaries/thesis_figures'),
        help='Directory where the combined thesis figure bundle will be written.',
    )
    parser.add_argument('--skip-schematic', action='store_true')
    parser.add_argument('--skip-core', action='store_true')
    parser.add_argument('--skip-clean-summary', action='store_true')
    parser.add_argument('--skip-frozen', action='store_true')
    parser.add_argument(
        '--allow-missing',
        action='store_true',
        help='Skip missing figure inputs instead of failing. Rule-decoding outputs are always optional.',
    )
    return parser.parse_args()


def run_command(cmd, label, strict=True):
    print('\n=== {} ==='.format(label), flush=True)
    print(' '.join(str(part) for part in cmd), flush=True)
    try:
        subprocess.run(cmd, check=True)
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        if strict:
            raise
        print('skipping {}: {}'.format(label, exc), flush=True)


def copy_rule_decoding_outputs(stochastic_root, output_dir):
    rule_dir = stochastic_root / 'rule_decoding_small'
    copied = []
    for ext in ['png', 'pdf', 'svg']:
        src = rule_dir / f'rule_decoding_summary.{ext}'
        if src.exists():
            dst = output_dir / f'figure_rule_decoding_summary.{ext}'
            shutil.copy2(src, dst)
            copied.append(dst)
    for name in ['rule_decoding_summary.csv', 'rule_decoding_delta_summary.csv']:
        src = rule_dir / name
        if src.exists():
            dst = output_dir / name
            shutil.copy2(src, dst)
            copied.append(dst)
    if copied:
        print('copied rule-decoding outputs:', flush=True)
        for path in copied:
            print('  {}'.format(path), flush=True)
    else:
        print('rule-decoding outputs not found yet; skipping optional decoding figure', flush=True)


def write_readme(output_dir):
    text = """# Thesis Figure Bundle

Generated by `scripts/make_thesis_chapter_figures.py`.

Expected core files:

- `figure_model_task_schematic.*`: model/task schematic.
- `stochastic_bottleneck_core_results.*`: main behavior, activity, and causal result figure.
- `stochastic_bottleneck_clean_summary.*`: cleaner three-panel summary with lowercase panel labels.
- `core_results_table.md`: compact table for the main stochastic-bottleneck results.
- `manuscript_core_results_table.md`: manuscript-style behavior/activity/causal tables.
- `figure_frozen_backbone_robustness.*`: frozen-backbone robustness/control figure.
- `frozen_backbone_robustness_table.md`: frozen-backbone robustness table.
- `figure_rule_decoding_summary.*`: optional decoding validation figure, copied only if available.

Interpretation guardrail:

The main claim should rest on the stochastic hidden-switch analyses and causal
VIP/SST perturbations. The frozen-backbone figure is a control showing that
feedback/readout-only fine-tuning produces very small route-dependent changes.
"""
    (output_dir / 'README.md').write_text(text)


def main():
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[1]
    scripts_dir = repo_root / 'scripts'
    stochastic_root = Path(args.stochastic_summaries_root).expanduser().resolve()
    frozen_root = Path(args.frozen_root).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    if not args.skip_schematic:
        run_command(
            [
                sys.executable,
                str(scripts_dir / 'make_stochastic_bottleneck_schematic.py'),
                '--output-dir',
                str(output_dir),
            ],
            'model/task schematic',
            strict=not args.allow_missing,
        )

    if not args.skip_core:
        run_command(
            [
                sys.executable,
                str(scripts_dir / 'make_stochastic_bottleneck_results_table_figure.py'),
                '--summaries-root',
                str(stochastic_root),
                '--output-dir',
                str(output_dir),
            ],
            'core stochastic-bottleneck results',
            strict=not args.allow_missing,
        )

    if not args.skip_clean_summary:
        run_command(
            [
                sys.executable,
                str(scripts_dir / 'make_stochastic_bottleneck_clean_summary_figure.py'),
                '--tables-dir',
                str(output_dir),
                '--output-dir',
                str(output_dir),
            ],
            'clean three-panel stochastic-bottleneck summary',
            strict=not args.allow_missing,
        )

    if not args.skip_frozen:
        run_command(
            [
                sys.executable,
                str(scripts_dir / 'make_frozen_backbone_robustness_figure.py'),
                '--frozen-root',
                str(frozen_root),
                '--output-dir',
                str(output_dir),
            ],
            'frozen-backbone robustness',
            strict=not args.allow_missing,
        )

    copy_rule_decoding_outputs(stochastic_root, output_dir)
    write_readme(output_dir)
    print('\nFigure bundle written to {}'.format(output_dir), flush=True)


if __name__ == '__main__':
    main()
